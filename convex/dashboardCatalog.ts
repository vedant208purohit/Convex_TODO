// Fast Index Maps for Catalog Lookups
const CATALOG_BY_ID = new Map<string, WidgetDefinition>(
  WIDGET_CATALOG.map((w) => [w.widgetId, w])
);

export function getWidgetDefinition(widgetId: string): WidgetDefinition | undefined {
  return CATALOG_BY_ID.get(widgetId);
}

export function listAllWidgets(): WidgetDefinition[] {
  return WIDGET_CATALOG;
}

export function getWidgetsByCategory(category: WidgetCategory): WidgetDefinition[] {
  return WIDGET_CATALOG.filter((w) => w.category === category);
}

export function searchWidgets(queryText: string): WidgetDefinition[] {
  const q = queryText.trim().toLowerCase();
  if (!q) return WIDGET_CATALOG;
  return WIDGET_CATALOG.filter(
    (w) =>
      w.name.toLowerCase().includes(q) ||
      w.description.toLowerCase().includes(q) ||
      w.category.toLowerCase().includes(q) ||
      (w.subcategory && w.subcategory.toLowerCase().includes(q)) ||
      w.widgetId.toLowerCase().includes(q)
  );
}

